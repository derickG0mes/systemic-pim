CREATE OR ALTER TRIGGER dbo.trg_abrir_comanda ON dbo.COMANDA
AFTER INSERT
AS
BEGIN
    SET NOCOUNT ON;
    UPDATE M
    SET STATUS_MESA = 'OCUPADA'
    FROM dbo.MESA AS M
    INNER JOIN inserted AS I ON I.ID_MESA = M.ID_MESA
    WHERE I.STATUS_COMANDA = 'ABERTA';
END;
GO

CREATE OR ALTER TRIGGER dbo.trg_atualizar_valor_total ON dbo.ITEM_COMANDA
AFTER INSERT, UPDATE, DELETE
AS
BEGIN
    SET NOCOUNT ON;
    UPDATE C
    SET VALOR_TOTAL = ISNULL((
        SELECT SUM(IC.QTD_PRODUTO * IC.PRECO_UNITARIO_PAGO)
        FROM dbo.ITEM_COMANDA AS IC
        WHERE IC.ID_COMANDA = C.ID_COMANDA
    ), 0)
    FROM dbo.COMANDA AS C
    WHERE C.ID_COMANDA IN (
        SELECT ID_COMANDA FROM inserted
        UNION
        SELECT ID_COMANDA FROM deleted
    );
END;
GO

CREATE OR ALTER TRIGGER dbo.trg_fechar_comanda ON dbo.DETALHE_PAGAMENTO
AFTER INSERT
AS
BEGIN
    SET NOCOUNT ON;
    UPDATE C
    SET STATUS_COMANDA = 'FECHADA',
        DATA_FECHADA = CAST(GETUTCDATE() AT TIME ZONE 'UTC' AT TIME ZONE 'E. South America Standard Time' AS DATETIME)
    FROM dbo.COMANDA AS C
    INNER JOIN inserted AS I ON I.ID_COMANDA = C.ID_COMANDA;

    UPDATE M
    SET STATUS_MESA = 'DISPONIVEL'
    FROM dbo.MESA AS M
    INNER JOIN dbo.COMANDA AS C ON C.ID_MESA = M.ID_MESA
    INNER JOIN inserted AS I ON I.ID_COMANDA = C.ID_COMANDA
    WHERE C.STATUS_COMANDA = 'FECHADA';
END;
GO

