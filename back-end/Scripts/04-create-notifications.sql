USE [DB_RESTAURANTE];
GO

IF OBJECT_ID(N'dbo.NOTIFICACAO', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.NOTIFICACAO
    (
        ID_NOTIFICACAO INT IDENTITY(1,1) NOT NULL
            CONSTRAINT PK_NOTIFICACAO PRIMARY KEY,
        ID_FUNCIONARIO INT NOT NULL,
        TIPO NVARCHAR(40) NOT NULL,
        TITULO NVARCHAR(120) NOT NULL,
        MENSAGEM NVARCHAR(500) NOT NULL,
        LINK NVARCHAR(200) NOT NULL,
        CRIADA_EM DATETIME2 NOT NULL CONSTRAINT DF_NOTIFICACAO_CRIADA_EM DEFAULT (SYSUTCDATETIME()),
        LIDA_EM DATETIME2 NULL,
        CONSTRAINT FK_NOTIFICACAO_FUNCIONARIO FOREIGN KEY (ID_FUNCIONARIO)
            REFERENCES dbo.FUNCIONARIO(ID_FUNCIONARIO)
    );
END;
GO

IF NOT EXISTS (
    SELECT 1 FROM sys.indexes
    WHERE name = N'IX_NOTIFICACAO_FUNCIONARIO_CRIADA'
      AND object_id = OBJECT_ID(N'dbo.NOTIFICACAO'))
BEGIN
    CREATE INDEX IX_NOTIFICACAO_FUNCIONARIO_CRIADA
        ON dbo.NOTIFICACAO(ID_FUNCIONARIO, CRIADA_EM DESC);
END;
GO

IF NOT EXISTS (
    SELECT 1 FROM sys.indexes
    WHERE name = N'IX_NOTIFICACAO_FUNCIONARIO_LIDA'
      AND object_id = OBJECT_ID(N'dbo.NOTIFICACAO'))
BEGIN
    CREATE INDEX IX_NOTIFICACAO_FUNCIONARIO_LIDA
        ON dbo.NOTIFICACAO(ID_FUNCIONARIO, LIDA_EM)
        INCLUDE (CRIADA_EM);
END;
GO
