USE [DB_RESTAURANTE];
GO

IF OBJECT_ID(N'dbo.DISPOSITIVO_PUSH', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.DISPOSITIVO_PUSH
    (
        ID_DISPOSITIVO_PUSH INT IDENTITY(1,1) NOT NULL
            CONSTRAINT PK_DISPOSITIVO_PUSH PRIMARY KEY,
        ID_FUNCIONARIO INT NOT NULL,
        TOKEN NVARCHAR(200) NOT NULL,
        PLATAFORMA NVARCHAR(20) NOT NULL,
        CRIADO_EM DATETIME2 NOT NULL CONSTRAINT DF_DISPOSITIVO_PUSH_CRIADO_EM DEFAULT (SYSUTCDATETIME()),
        ATUALIZADO_EM DATETIME2 NOT NULL CONSTRAINT DF_DISPOSITIVO_PUSH_ATUALIZADO_EM DEFAULT (SYSUTCDATETIME()),
        CONSTRAINT FK_DISPOSITIVO_PUSH_FUNCIONARIO FOREIGN KEY (ID_FUNCIONARIO)
            REFERENCES dbo.FUNCIONARIO(ID_FUNCIONARIO)
    );
END;
GO

IF NOT EXISTS (
    SELECT 1 FROM sys.indexes
    WHERE name = N'UX_DISPOSITIVO_PUSH_TOKEN'
      AND object_id = OBJECT_ID(N'dbo.DISPOSITIVO_PUSH'))
BEGIN
    CREATE UNIQUE INDEX UX_DISPOSITIVO_PUSH_TOKEN
        ON dbo.DISPOSITIVO_PUSH(TOKEN);
END;
GO

IF NOT EXISTS (
    SELECT 1 FROM sys.indexes
    WHERE name = N'IX_DISPOSITIVO_PUSH_FUNCIONARIO'
      AND object_id = OBJECT_ID(N'dbo.DISPOSITIVO_PUSH'))
BEGIN
    CREATE INDEX IX_DISPOSITIVO_PUSH_FUNCIONARIO
        ON dbo.DISPOSITIVO_PUSH(ID_FUNCIONARIO);
END;
GO
