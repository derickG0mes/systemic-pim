-- =========================================================================
-- CRIAÇÃO DAS TABELAS
-- =========================================================================

CREATE TABLE FUNCIONARIO (
    ID_FUNCIONARIO INT PRIMARY KEY IDENTITY(1,1),
    NOME_FUNCIONARIO VARCHAR(100) NOT NULL,
    EMAIL_FUNCIONARIO VARCHAR(100) NOT NULL UNIQUE,
    CARGO_FUNCIONARIO VARCHAR(20) NOT NULL,
    CPF_FUNCIONARIO CHAR(11) NOT NULL UNIQUE,
    TELEFONE_FUNCIONARIO CHAR(11) NOT NULL,
    PASSWORD_FUNCIONARIO VARCHAR(255) NOT NULL,
    MFA_SECRET VARCHAR(100) NULL,
    STATUS_FUNCIONARIO VARCHAR(10) NOT NULL DEFAULT 'ATIVO',
    ROLE VARCHAR(20) NOT NULL DEFAULT 'employee',
    LOGIN_ATTEMPTS INT NOT NULL DEFAULT 0,
    LOCKED_UNTIL DATETIME NULL
);

CREATE TABLE CLIENTE (
    ID_CLIENTE INT PRIMARY KEY IDENTITY(1,1),
    NOME_CLIENTE VARCHAR(100) NOT NULL,
    TELEFONE_CLIENTE CHAR(11) NULL,
    FEEDBACK VARCHAR(10) NULL
);

CREATE TABLE MESA (
    ID_MESA INT PRIMARY KEY IDENTITY(1,1),
    NUMERO_MESA INT NOT NULL,
    STATUS_MESA VARCHAR(20) NOT NULL DEFAULT 'DISPONIVEL',
    CAPACIDADE_MESA INT NOT NULL
);

CREATE TABLE FORMA_PAGAMENTO (
    ID_FORMA_PAGAMENTO INT PRIMARY KEY IDENTITY(1,1),
    NOME_FORMA_PAGAMENTO VARCHAR(20) NOT NULL UNIQUE
);

CREATE TABLE PRODUTO (
    ID_PRODUTO INT PRIMARY KEY IDENTITY(1,1),
    NOME_PRODUTO VARCHAR(45) NOT NULL,
    DESCRICAO_PRODUTO VARCHAR(100) NULL,
    PRECO_CUSTO DECIMAL(10,2) NULL,
    PRECO_PRODUTO DECIMAL(10,2) NOT NULL,
    PRECO_VENDA DECIMAL(10,2) NULL,
    QTD_ESTOQUE INT NOT NULL,
    ESTOQUE_MINIMO INT NOT NULL DEFAULT 5,
    STATUS_PRODUTO VARCHAR(20) NOT NULL DEFAULT 'DISPONIVEL',
    CATEGORIA_PRODUTO VARCHAR(20) NOT NULL DEFAULT 'PRINCIPAL'
);

CREATE TABLE RESERVA (
    ID_RESERVA INT PRIMARY KEY IDENTITY(1,1),
    ID_CLIENTE INT NOT NULL,
    ID_MESA INT NOT NULL,
    DATA_RESERVA DATETIME NOT NULL,
    STATUS_RESERVA VARCHAR(20) NOT NULL DEFAULT 'DISPONIVEL',
    CONSTRAINT FK_RESERVA_CLIENTE FOREIGN KEY (ID_CLIENTE) REFERENCES CLIENTE(ID_CLIENTE),
    CONSTRAINT FK_RESERVA_MESA FOREIGN KEY (ID_MESA) REFERENCES MESA(ID_MESA)
);

CREATE TABLE COMANDA (
    ID_COMANDA INT PRIMARY KEY IDENTITY(1,1),
    DATA_ABERTA DATETIME NOT NULL DEFAULT CAST(GETUTCDATE() AT TIME ZONE 'UTC' AT TIME ZONE 'E. South America Standard Time' AS DATETIME),
    DATA_FECHADA DATETIME NULL,
    STATUS_COMANDA VARCHAR(10) NOT NULL DEFAULT 'ABERTA',
    ID_MESA INT NOT NULL,
    ID_CLIENTE INT NOT NULL,
    VALOR_TOTAL DECIMAL(18,2) NOT NULL DEFAULT 0,
    CONSTRAINT FK_COMANDA_MESA FOREIGN KEY (ID_MESA) REFERENCES MESA(ID_MESA),
    CONSTRAINT FK_COMANDA_CLIENTE FOREIGN KEY (ID_CLIENTE) REFERENCES CLIENTE(ID_CLIENTE)
);

CREATE TABLE ITEM_COMANDA (
    ID_ITEM_COMANDA INT PRIMARY KEY IDENTITY(1,1),
    QTD_PRODUTO INT NOT NULL,
    PRECO_UNITARIO_PAGO DECIMAL(10,2) NOT NULL,
    STATUS_ITEM VARCHAR(20) NOT NULL DEFAULT 'PREPARAR',
    ID_PRODUTO INT NOT NULL,
    ID_COMANDA INT NOT NULL,
    CONSTRAINT FK_ITEM_COMANDA_PRODUTO FOREIGN KEY (ID_PRODUTO) REFERENCES PRODUTO(ID_PRODUTO),
    CONSTRAINT FK_ITEM_COMANDA_COMANDA FOREIGN KEY (ID_COMANDA) REFERENCES COMANDA(ID_COMANDA)
);

CREATE TABLE DETALHE_PAGAMENTO (
    ID_DETALHE_PAGAMENTO INT PRIMARY KEY IDENTITY(1,1),
    VALOR_PAGO DECIMAL(10,2) NOT NULL,
    TROCO DECIMAL(10,2) NOT NULL,
    DATA_PAGAMENTO DATETIME NOT NULL DEFAULT CAST(GETUTCDATE() AT TIME ZONE 'UTC' AT TIME ZONE 'E. South America Standard Time' AS DATETIME),
    STATUS_PAGAMENTO VARCHAR(10) NOT NULL DEFAULT 'PAGO',
    ID_COMANDA INT NOT NULL,
    ID_FORMA_PAGAMENTO INT NOT NULL,
    ID_FUNCIONARIO INT NOT NULL,
    CONSTRAINT FK_DETALHE_PAGAMENTO_COMANDA FOREIGN KEY (ID_COMANDA) REFERENCES COMANDA(ID_COMANDA),
    CONSTRAINT FK_DETALHE_PAGAMENTO_FORMA FOREIGN KEY (ID_FORMA_PAGAMENTO) REFERENCES FORMA_PAGAMENTO(ID_FORMA_PAGAMENTO),
    CONSTRAINT FK_DETALHE_PAGAMENTO_FUNC FOREIGN KEY (ID_FUNCIONARIO) REFERENCES FUNCIONARIO(ID_FUNCIONARIO)
);

CREATE TABLE DESPESAS (
    ID_DESPESA INT PRIMARY KEY IDENTITY(1,1),
    DESCRICAO_DESPESA VARCHAR(100) NOT NULL,
    VALOR_DESPESA DECIMAL(10,2) NOT NULL,
    CATEGORIA_DESPESA VARCHAR(50) NOT NULL,
    DATA_DESPESA DATETIME NOT NULL,
    ID_FORMA_PAGAMENTO INT NOT NULL,
    CONSTRAINT FK_DESPESAS_FORMA FOREIGN KEY (ID_FORMA_PAGAMENTO) REFERENCES FORMA_PAGAMENTO(ID_FORMA_PAGAMENTO)
);

CREATE TABLE LOG_COMANDA (
    ID_LOG_COMANDA INT PRIMARY KEY IDENTITY(1,1),
    DATA_LOG DATETIME NOT NULL DEFAULT CAST(GETUTCDATE() AT TIME ZONE 'UTC' AT TIME ZONE 'E. South America Standard Time' AS DATETIME),
    ACAO_LOG VARCHAR(50) NOT NULL,
    ID_COMANDA INT NOT NULL,
    ID_FUNCIONARIO INT NOT NULL,
    CONSTRAINT FK_LOG_COMANDA_COMANDA FOREIGN KEY (ID_COMANDA) REFERENCES COMANDA(ID_COMANDA),
    CONSTRAINT FK_LOG_COMANDA_FUNCIONARIO FOREIGN KEY (ID_FUNCIONARIO) REFERENCES FUNCIONARIO(ID_FUNCIONARIO)
);

CREATE TABLE LOG_SISTEMA (
    ID_LOG_SISTEMA INT PRIMARY KEY IDENTITY(1,1),
    DATA_LOG DATETIME2 NOT NULL DEFAULT (CAST(GETUTCDATE() AT TIME ZONE 'UTC' AT TIME ZONE 'E. South America Standard Time' AS DATETIME2)),
    TIPO_LOG VARCHAR(50) NOT NULL,
    DESCRICAO_LOG VARCHAR(500) NOT NULL,
    USUARIO_LOG VARCHAR(100) NULL,
    DADO_ANTERIOR VARCHAR(MAX) NULL,
    DADO_NOVO VARCHAR(MAX) NULL
);

GO

